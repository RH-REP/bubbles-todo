/* 地点の ID（保存に使う。並びを変えても選んだ地域がずれないよう、番号ではなく名前で持つ） */
export function pointId(p) { return p[0] + '/' + p[1]; }
export function pointLabel(p) { return p[0] + ' ' + p[1] + '（' + p[2] + '）'; }
export function findPoint(id) { return POINTS.findIndex(p => pointId(p) === id); }

/* 頼む URL。地点はいつも全部（どの地域を見ているかを URL に出さない） */
export function buildUrl(points = POINTS, days = DAYS) {
  const lat = points.map(p => p[3].toFixed(2)).join(',');
  const lon = points.map(p => p[4].toFixed(2)).join(',');
  return API + '?latitude=' + lat + '&longitude=' + lon
    + '&daily=weather_code,temperature_2m_max,temperature_2m_min'
    + '&timezone=Asia%2FTokyo&forecast_days=' + days;
}

function num(v) { return (typeof v === 'number' && Number.isFinite(v)) ? v : null; }

/* 返事（地点が複数なら配列、1つならその物）を、保存の形にする。
   { days: ['YYYY-MM-DD', …], pts: [{ c: [天気の番号], hi: [最高], lo: [最低] }, …] }
   地点の数が頼んだ数と違うときは、ずれた地域に別の天気を出さないよう、読めなかったことにする */
export function parseForecast(json, count = POINTS.length) {
  const list = Array.isArray(json) ? json : (json && typeof json === 'object' ? [json] : []);
  if (list.length !== count) throw new Error('地点の数が合わない（' + list.length + '／' + count + '）');
  let days = null;
  const pts = list.map(o => {
    const d = o && o.daily;
    if (!d || !Array.isArray(d.time)) throw new Error('予報の形が読めない');
    if (!days) days = d.time.map(String);
    const pick = a => d.time.map((_, i) => num(Array.isArray(a) ? a[i] : null));
    return { c: pick(d.weather_code), hi: pick(d.temperature_2m_max), lo: pick(d.temperature_2m_min) };
  });
  return { days: days || [], pts };
}

/* WMO の天気の番号 → 印と名前 */
export function wxOf(code) {
  const c = num(code);
  if (c === null) return null;
  if (c === 0) return { icon: '☀️', name: '快晴' };
  if (c === 1) return { icon: '🌤️', name: '晴れ' };
  if (c === 2) return { icon: '⛅', name: '晴れ時々くもり' };
  if (c === 3) return { icon: '☁️', name: 'くもり' };
  if (c === 45 || c === 48) return { icon: '🌫️', name: '霧' };
  if (c >= 51 && c <= 57) return { icon: '🌦️', name: '霧雨' };
  if (c >= 61 && c <= 67) return { icon: '☂️', name: '雨' };
  if (c >= 71 && c <= 77) return { icon: '❄️', name: '雪' };
  if (c >= 80 && c <= 82) return { icon: '🌦️', name: 'にわか雨' };
  if (c === 85 || c === 86) return { icon: '🌨️', name: 'にわか雪' };
  if (c >= 95 && c <= 99) return { icon: '⛈️', name: '雷雨' };
  return { icon: '・', name: '不明' };
}

/* 保存したもののうち、その地点のその日の予報。無ければ null
   返り値 = { icon, name, hi, lo }（hi・lo は四捨五入した整数か null） */
export function forecastFor(data, idx, key) {
  if (!data || !Array.isArray(data.days) || !Array.isArray(data.pts)) return null;
  const p = data.pts[idx];
  const i = data.days.indexOf(key);
  if (!p || i < 0) return null;
  const w = wxOf(p.c && p.c[i]);
  const r = v => (num(v) === null ? null : Math.round(v));
  const hi = r(p.hi && p.hi[i]), lo = r(p.lo && p.lo[i]);
  if (!w && hi === null && lo === null) return null;
  return { icon: w ? w.icon : '', name: w ? w.name : '', hi, lo };
}

/* 大きさの札（バイト → 「82 KB」） */
export function sizeLabel(bytes) {
  const b = Number(bytes) || 0;
  if (b < 1024) return b + ' B';
  if (b < 1024 * 1024) return Math.round(b / 1024) + ' KB';
  return (b / 1024 / 1024).toFixed(1) + ' MB';
}

/* ---- 端末に置く ---- */
function ls() { try { return globalThis.localStorage || null; } catch (e) { return null; } }

export function loadData() {
  const s = ls();
  try {
    const o = JSON.parse((s && s.getItem(DATA_KEY)) || 'null');
    return (o && Array.isArray(o.days) && Array.isArray(o.pts) && o.pts.length === POINTS.length) ? o : null;
  } catch (e) { return null; }
}
function saveData(o) {
  const s = ls();
  try { if (s) s.setItem(DATA_KEY, JSON.stringify(o)); } catch (e) { /* 置けなくても、今の画面には出る */ }
}

/* 選んだ地域の番号。選んでいなければ -1 */
export function loadArea() {
  const s = ls();
  let id = '';
  try { id = (s && s.getItem(AREA_KEY)) || ''; } catch (e) { id = ''; }
  return id ? findPoint(id) : -1;
}
export function saveArea(idx) {
  const s = ls();
  try {
    if (!s) return;
    if (idx >= 0 && POINTS[idx]) s.setItem(AREA_KEY, pointId(POINTS[idx]));
    else s.removeItem(AREA_KEY);
  } catch (e) { /* 覚えられなくても、今の画面には出る */ }
}

/* 取ってきて置く。返り値は保存したもの（{ at, bytes, days, pts }）。届かなければ Error を投げる。
   bytes は受け取った本文の大きさ（圧縮を解いたあと。網の上はこれより小さい） */
export async function fetchForecast(fetchFn = globalThis.fetch) {
  let res;
  try {
    res = await fetchFn(buildUrl(), { cache: 'no-store' });
  } catch (e) {
    throw new Error('天気の API に届かなかった（網が無いか、止められた）');
  }
  const text = await res.text();
  if (!res.ok) {
    let why = '';
    try { why = (JSON.parse(text) || {}).reason || ''; } catch (e) { why = ''; }
    throw new Error('天気の API が受け付けなかった（' + res.status + (why ? '：' + String(why).slice(0, 80) : '') + '）');
  }
  let json;
  try { json = JSON.parse(text); } catch (e) { throw new Error('天気の返事が読めない'); }
  const parsed = parseForecast(json);
  const bytes = new TextEncoder().encode(text).length;
  const out = { at: Date.now(), bytes, days: parsed.days, pts: parsed.pts };
  saveData(out);
  return out;
}
